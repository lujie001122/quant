#!/bin/bash
# chase（追涨杀跌）每日数据管道 — 盘后 15:10 跑一次，串在现有盘后任务里即可
#   1) 交易日历追加真实成交日（sh000001）
#   2) 全池前复权日线增量（重叠段比对，除息重标自动全量重抓）
#   3) 不复权日线（腾讯批量行情，涨跌停/实物价口径）
#   4) 份额 + 净值（复用 flow_data：上交所/深交所/东财，PIT 份额 T-1）
#
# 幂等：同一天重复跑只会覆盖当日那根，不会重复追加。
cd "$(dirname "$0")/.." || exit 1
exec .venv/bin/python3 chase_data.py --update --jobs 16
